import {chromium} from "playwright";
import {strict as assert} from "node:assert";
import {mkdirSync} from "node:fs";
const base="http://127.0.0.1:8765";
mkdirSync("test-results",{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1380,height:900},deviceScaleFactor:1});
const failures=[];
page.on("pageerror",e=>failures.push("Browser JS error: "+e.message));
page.on("response",r=>{if(r.url().startsWith(base)&&r.status()>=400)failures.push("HTTP "+r.status()+" "+r.url());});
try{
 await page.goto(base+"/index.html",{waitUntil:"networkidle"});
 await page.locator(".choice-home").waitFor();
 assert.equal(await page.locator(".choice-category").count(),8,"eight categories on homepage");
 assert.ok((await page.locator("#progressCounter").innerText()).includes("42"),"42 game counter");
 const pathLink=page.locator('header a[href="starttest.html"]');
 assert.ok((await pathLink.innerText()).includes("Find din læsevej"),"consistent navigation");
 assert.equal(await pathLink.evaluate(el=>getComputedStyle(el).textDecorationLine),"none","header link not underlined");
 assert.equal(await page.locator(".parent-info").count(),1,"parent information is present");
 await page.locator(".parent-info summary").click();
 assert.equal(await page.locator(".parent-info").getAttribute("open"),"","parent information opens");
 assert.ok((await page.locator(".parent-info").innerText()).includes("10–15 minutter"),"practical advice for parents");
 assert.ok((await page.locator(".parent-info").innerText()).includes("Ikke en prøve"),"transparent limits");
 await page.screenshot({path:"test-results/review-home-desktop.png",fullPage:true});
 await page.locator(".lm-launch").click();
 assert.ok(await page.locator("#lm-panel").isVisible(),"owl can be opened");
 assert.ok(!(await page.locator(".lm-stop").isVisible()),"Stop sound hidden when idle");
 await page.locator(".lm-close").click();
 assert.ok(!(await page.locator("#lm-panel").isVisible()),"owl closes");
 // A pupil must not be able to clear all progress without confirmation.
 await page.evaluate(()=>localStorage.setItem("laese3c_stats",JSON.stringify({maze:{best:1,last:1,total:4,plays:1}})));
 await page.reload({waitUntil:"networkidle"});
 await page.getByRole("button",{name:/Til læreren/}).click();
 await page.locator("#teacher-heading").waitFor();
 assert.ok((await page.locator(".modal").innerText()).includes("To forslag til et øvepas"));
 assert.ok((await page.locator(".modal").innerText()).includes("15. november 2026"));
 const deleteButton=page.getByRole("button",{name:/Ryd lokale øveresultater/});
 page.once("dialog",dialog=>dialog.dismiss());
 await deleteButton.click();
 const afterDismiss=await page.evaluate(()=>JSON.parse(localStorage.getItem("laese3c_stats")||"{}"));
 assert.ok(afterDismiss.maze,"cancel keeps progress");
 page.once("dialog",dialog=>dialog.accept());
 await deleteButton.click();
 const afterAccept=await page.evaluate(()=>JSON.parse(localStorage.getItem("laese3c_stats")||"{}"));
 assert.deepEqual(Object.keys(afterAccept),[],"confirm clears progress");
 await page.goto(base+"/index.html#til-foraeldre",{waitUntil:"networkidle"});
 assert.equal(await page.locator(".parent-info").getAttribute("open"),"","parent link opens the information");
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+"/index.html",{waitUntil:"networkidle"});
 await page.locator(".choice-home").waitFor();
 await page.screenshot({path:"test-results/review-home-mobile.png",fullPage:true});
 await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));
 await page.waitForTimeout(200);
 const geometry=await page.evaluate(()=>{
  const foot=document.querySelector("footer .foot-inner span"),owl=document.querySelector("#laesemakker-root .lm-launch");
  const a=foot.getBoundingClientRect(),b=owl.getBoundingClientRect();
  return {firstFooterText:{top:a.top,bottom:a.bottom,left:a.left,right:a.right},owl:{top:b.top,bottom:b.bottom,left:b.left,right:b.right},width:document.documentElement.scrollWidth,viewport:innerWidth};
 });
 assert.ok(geometry.width<=geometry.viewport+2,"no mobile overflow: "+JSON.stringify(geometry));
 const overlap=(a,b)=>a.left<b.right&&b.left<a.right&&a.top<b.bottom&&b.top<a.bottom;
 assert.ok(!overlap(geometry.firstFooterText,geometry.owl),"owl does not cover footer: "+JSON.stringify(geometry));
 await page.goto(base+"/starttest.html",{waitUntil:"networkidle"});
 await page.locator("#screen .hero").waitFor();
 assert.ok((await page.locator("#screen").innerText()).includes("Hvad er du mest sikker på:"));
 assert.ok((await page.locator("#screen").innerText()).includes("undersøger ikke selvstændigt"));
 assert.equal(await page.evaluate(()=>window.Laesestart.getQuestions().length),24);
 await page.evaluate(()=>{const t=window.Laesestart;for(let n=0;n<24;n++){t.answer(0);t.go(1);}});
 assert.ok((await page.locator("#screen").innerText()).includes("42 spil i værkstedet"),"start test recommends correct total");
 await page.screenshot({path:"test-results/review-starttest-mobile.png",fullPage:true});
 await page.goto(base+"/st3-traening.html?spil=vocab&niveau=1&omraade=ordforraad",{waitUntil:"networkidle"});
 const href=await page.locator("a[data-home]").first().getAttribute("href");
 assert.equal(href,"index.html?omraade=ordforraad","vocabulary game goes back to vocabulary category");
 await page.goto(base+"/st3-traening.html",{waitUntil:"networkidle"});
 assert.ok((await page.locator("#app").innerText()).includes("af 42 spil er gennemført"),"trainer progress shows 42");
 assert.equal(failures.length,0,failures.join(" | "));
 console.log("PASS browser: consistent navigation, eight areas, parent information, validated erasure consent, owl audio idle, footer clearance, 24-question start test, 42 counts, mobile no overflow, vocabulary return route.");
}finally{await browser.close();}
