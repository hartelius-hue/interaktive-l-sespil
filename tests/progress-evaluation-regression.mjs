import {readFileSync} from "node:fs";
import {strict as assert} from "node:assert";
import {runInNewContext,Script} from "node:vm";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const idx=read("index.html"),trainer=read("st3-traening.html"),vocab=read("ordforraad-spil.js"),html=read("ordforraad-spil.html"),goals=read("laeringsmaal.js"),progress=read("fremgang-3c.js");
function inlineScripts(t){return [...t.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.trim());}
for(const [file,code] of [["index.html",idx],["st3-traening.html",trainer]]){
 for(const [i,js] of inlineScripts(code).entries())assert.doesNotThrow(()=>new Script(js,{filename:file+":"+i}),file+" inline JS "+i);
 assert.ok(code.includes('src="fremgang-3c.js"'),file+" shared progress script is loaded");
}
assert.ok(html.includes('src="fremgang-3c.js"'),"vocabulary app uses same progress store");
for(const [file,js] of [["laeringsmaal.js",goals],["fremgang-3c.js",progress],["ordforraad-spil.js",vocab]])assert.doesNotThrow(()=>new Script(js),file+" syntax");
assert.ok(goals.includes('.replace(/\\s+/g," ")'),"strip whitespace only");
assert.ok(!goals.includes('.replace(/s+/g," ")'),"regression: must not strip letter s");
const w={};runInNewContext(goals,{window:w});
const goalsApi=w.Laeringsmaal;
assert.equal(goalsApi.ids.length,42,"all 42 games have learning goals");
const detail="To bøger nævnes. Det er vigtigt at holde styr på, hvilken bog hun lægger fra sig.";
for(const id of goalsApi.ids){
 const html=goalsApi.result(id,1,4,"choice",[detail]);
 assert.ok(html.includes("holde styr på"),id+": preserve s in styr");
 assert.ok(html.includes("fra sig"),id+": preserve s in sig");
 assert.ok(!html.includes("holde tyr på"),id+": no broken word");
 assert.ok(!html.includes("fra ig"),id+": no broken word");
 assert.ok(html.includes("Hvad øvede jeg"),id+": result title");
 assert.ok(goalsApi.intro(id).includes("Det øver jeg"),id+": intro");
}
const legacy={maze:{best:2,last:1,total:4,plays:1},picture:{best:0,last:0,total:4,plays:1}};
const map=new Map([["laese3c_stats",JSON.stringify(legacy)],["laese3c_extra_done",JSON.stringify(["vrovle","picture","vrovle"])]]);
const storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
const shared={localStorage:storage,dispatchEvent(){},addEventListener(){}};
runInNewContext(progress,{window:shared,Event:class{constructor(type){this.type=type;}}});
const p=shared.LaeseFremgang;
assert.deepEqual(Array.from(p.completedIds(["maze","picture","vrovle","minihistorie"])),["maze","picture","vrovle"],"old and new records merge without duplicate");
assert.equal(p.count(["maze","picture","vrovle"]),3);
assert.equal(p.has("minihistorie"),false);
assert.equal(p.record("minihistorie"),true,"records extra game");
assert.equal(p.has("minihistorie"),true);
assert.equal(p.record("minihistorie"),true,"repeat is idempotent");
assert.equal(p.count(["maze","picture","vrovle","minihistorie"]),4);
assert.equal(p.record("../bad"),false,"invalid ids rejected");
const c0=idx.indexOf("const LEARNING_CATEGORIES="),c1=idx.indexOf(";\nconst EXTRA_CATALOG=",c0);
const cats=JSON.parse(idx.slice(c0+"const LEARNING_CATEGORIES=".length,c1));
assert.equal(cats.length,8);
const ids=cats.flatMap(c=>c.ids);
assert.equal(ids.length,42);
assert.equal(new Set(ids).size,42,"all games uniquely represented in exactly one category");
for(const c of cats)for(const id of c.ids)assert.ok(goalsApi.ids.includes(id),id+" needs goal");
assert.ok(idx.includes("String(finished)"),"category completion status");
assert.ok(idx.includes("String(isCompleted)"),"per-game completion state");
assert.ok(idx.includes("✓ Alle"),"whole category checkmark");
assert.ok(idx.includes("window.LaeseFremgang?.record(active)"),"original games save with shared register");
assert.ok(idx.includes("game.progressSaved"),"visible save confirmation");
assert.ok(idx.includes("window.addEventListener('pageshow',refreshSavedProgress)"),"restore from browser cache");
assert.ok(idx.includes("window.addEventListener('storage',e=>"),"other tabs refresh");
assert.ok(trainer.includes("function recordFinished(id){\n if(window.LaeseFremgang)"),"training games use shared store");
assert.ok(trainer.includes("✓ Alle"),"training categories show progress");
assert.ok(trainer.includes("progressInfo"),"training results show persisted completion");
assert.ok(vocab.includes("const saved=window.LaeseFremgang?window.LaeseFremgang.record(id)"),"new vocabulary use shared store");
assert.ok(vocab.includes("saveMessage"),"new vocabulary results display persisted completion");
assert.ok(p.clear(),"clearing local data succeeds");
assert.equal(p.completedIds().length,0,"no completed games remain after clearing");
const denyStorage={getItem(){return null;},setItem(){throw Error("blocked");},removeItem(){throw Error("blocked");}};
const blocked={localStorage:denyStorage,dispatchEvent(){}};
runInNewContext(progress,{window:blocked,Event:class{}});
assert.equal(blocked.LaeseFremgang.record("picture"),false,"does not invent saved progress if storage blocked");
assert.match(blocked.LaeseFremgang.notice(false),/kunne ikke gemme fluebenet/);
const suspicious=[goals,idx,trainer,vocab].flatMap((s,i)=>s.includes(".replace(/s+/g")?[i]:[]);
assert.deepEqual(suspicious,[],"no accidental s-deleting regex remains");
console.log("PASS evaluation & completion regression: 42 Danish feedback messages preserve s, 8 categories/42 unique games, migration, dedup, reset, blocked storage, 3 game engines.");
